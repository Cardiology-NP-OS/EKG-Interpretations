"use strict";

const assert = require("assert");
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const { canonicalManifestPayload, preflightDevelopmentRun, validateDevelopmentManifest } = require("../lib/development_evaluation_preflight");
const { payloadSha256 } = require("../lib/evaluation_signatures");
const { assertDevelopmentIdentityAllowed, validateSpentRegistry } = require("../lib/spent_dataset_registry");
const { stableJson } = require("../lib/evaluation_runtime");

const root = path.join(__dirname, "..");
const registry = JSON.parse(fs.readFileSync(path.join(root, "evaluation", "registries", "SPENT_DATASET_REGISTRY.json"), "utf8"));
const registrySignature = JSON.parse(fs.readFileSync(path.join(root, "evaluation", "registries", "SPENT_DATASET_REGISTRY.sig"), "utf8"));
const spentTrustStore = JSON.parse(fs.readFileSync(path.join(root, "evaluation", "keys", "SPENT_REGISTRY_SIGNERS.json"), "utf8"));

function sign(payload, keyId = "synthetic-development-signer") {
  const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");
  return {
    signature: {
      algorithm: "Ed25519",
      keyId,
      payloadSha256: payloadSha256(payload),
      signatureBase64: crypto.sign(null, Buffer.from(stableJson(payload), "utf8"), privateKey).toString("base64"),
    },
    trustStore: {
      keys: [{ keyId, algorithm: "Ed25519", status: "TRUSTED", publicKeyPem: publicKey.export({ type: "spki", format: "pem" }) }],
    },
  };
}

function makeManifest() {
  const manifest = {
    schema: "ekg-development-manifest-v1",
    benchmarkId: "SYNTHETIC-DEVELOPMENT-RPEAK-V1",
    benchmarkVersion: "1",
    splitRole: "development",
    clinicalAccuracyClaimed: false,
    datasetIdentity: {
      datasetId: "ECG-DATASET-SYNTHETIC-DEVELOPMENT",
      datasetFamily: "Synthetic development fixture",
      datasetRelease: "1",
      canonicalSource: "repository://synthetic-only",
      sourceManifestSha256: "1".repeat(64),
      aliases: ["synthetic-development-only"],
    },
    rights: {
      verificationStatus: "VERIFIED",
      commercialProductImprovement: "PERMITTED",
      rawRedistributionInRepository: false,
      licenseSpdxOrName: "Synthetic fixture generated by project",
      sourceUri: "repository://tests/development_evaluation_preflight.test.js",
      licenseFileSha256: "2".repeat(64),
      verifiedAtUtc: "2026-09-22T00:00:00Z",
    },
    records: [
      {
        recordHmacSha256: "3".repeat(64),
        patientHmacSha256: "4".repeat(64),
        parentRecordHmacSha256: null,
        splitRole: "development",
        patientIndependence: "VERIFIED",
        taskEligibility: "ELIGIBLE",
        sourceFileSha256: "5".repeat(64),
        labelSnapshotSha256: "6".repeat(64),
        nearDuplicateGroupSha256: "7".repeat(64),
        sampleRateHz: 250,
        durationSeconds: 10,
        subgroups: { source: "synthetic", lead: "II", sampleRateHz: "250" },
      },
    ],
  };
  manifest.manifestPayloadSha256 = payloadSha256(canonicalManifestPayload(manifest));
  return manifest;
}

const registryResult = validateSpentRegistry(registry, registrySignature, spentTrustStore, {
  minimumSequence: 1,
  expectedPayloadSha256: registrySignature.payloadSha256,
});
assert.equal(registryResult.pass, true);
assert.equal(registryResult.entryCount, 2);

assert.throws(
  () => assertDevelopmentIdentityAllowed({ datasetId: "RENAMED-SAFE-BENCHMARK", sourceManifestSha256: "cccef1f3529519db8f26a333c97a6872a7d0e3e5c64a1448b76b161fd87fb75f" }, registry),
  /SPENT_DATASET_DENIED:LUDB-QRS-V2-COVERAGE-V2-HOLDOUT-V1/,
);
assert.throws(
  () => assertDevelopmentIdentityAllowed({ canonicalSource: "https://physionet.org/content/mitdb/1.0.0/" }, registry),
  /SPENT_DATASET_DENIED:MIT-BIH-RPEAK-FULL-V1/,
);
assert.throws(
  () => validateSpentRegistry({ ...registry, sequence: 2 }, registrySignature, spentTrustStore),
  /EVAL_SIGNATURE_PAYLOAD_DIGEST_MISMATCH/,
);
assert.throws(
  () => validateSpentRegistry(registry, registrySignature, spentTrustStore, { minimumSequence: 2 }),
  /EVAL_SIGNATURE_ROLLBACK/,
);

const manifest = makeManifest();
const signedManifest = sign(canonicalManifestPayload(manifest));
const result = preflightDevelopmentRun({
  spentRegistry: registry,
  spentRegistrySignature: registrySignature,
  spentTrustStore,
  minimumSpentRegistrySequence: 1,
  expectedSpentRegistrySha256: registrySignature.payloadSha256,
  manifest,
  manifestSignature: signedManifest.signature,
  manifestTrustStore: signedManifest.trustStore,
});
assert.equal(result.pass, true);
assert.equal(result.recordCount, 1);
assert.equal(result.patientCount, 1);
assert.equal(result.clinicalAccuracyClaimed, false);

const selection = makeManifest();
selection.records[0].splitRole = "selection";
selection.manifestPayloadSha256 = payloadSha256(canonicalManifestPayload(selection));
assert.throws(() => validateDevelopmentManifest(selection), /DEVELOPMENT_ROLE_ONLY/);

const leaked = makeManifest();
leaked.records.push({ ...leaked.records[0], recordHmacSha256: "8".repeat(64), sourceFileSha256: "9".repeat(64), splitRole: "holdout" });
leaked.manifestPayloadSha256 = payloadSha256(canonicalManifestPayload(leaked));
assert.throws(() => validateDevelopmentManifest(leaked), /DEVELOPMENT_PATIENT_LEAKAGE/);

const unverifiedRights = makeManifest();
unverifiedRights.rights = { ...unverifiedRights.rights, verificationStatus: "UNVERIFIED" };
unverifiedRights.manifestPayloadSha256 = payloadSha256(canonicalManifestPayload(unverifiedRights));
assert.throws(() => validateDevelopmentManifest(unverifiedRights), /DEVELOPMENT_RIGHTS_UNVERIFIED/);

console.log("development evaluation preflight tests passed");
