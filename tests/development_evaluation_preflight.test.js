const registryResult = validateSpentRegistry(registry, registrySignature, spentTrustStore, {
  minimumSequence: 1,
  expectedPayloadSha256: registrySignature.payloadSha256,
});
assert.equal(registryResult.pass, true);
assert.equal(registryResult.entryCount, 2);

assert.throws(
  () => assertDevelopmentIdentityAllowed({ datasetId: "RENAMED-SAFE-BENCHMARK", sourceManifestSha256: "cccef1f3529519db8f26a333c97a6872a7d0e3e5c64a1448b76b161fd87fb75f" }, registry),
  /SPENT_DATASET_DENIED:LUDB-QRS-V2-COVERAGE-V2-HOLDOUT-V1/,
);
assert.throws(
  () => assertDevelopmentIdentityAllowed({ canonicalSource: "https://physionet.org/content/mitdb/1.0.0/" }, registry),
  /SPENT_DATASET_DENIED:MIT-BIH-RPEAK-FULL-V1/,
);
assert.throws(
  () => assertDevelopmentIdentityAllowed({ aliases: ["MITBIH"] }, registry),
  /SPENT_DATASET_DENIED:MIT-BIH-RPEAK-FULL-V1/,
);
assert.equal(assertDevelopmentIdentityAllowed({ datasetId: "ECG-DATASET-UNRELATED", datasetRelease: "1.0.0" }, registry), true);
assert.throws(
  () => assertDevelopmentIdentityAllowed({ datasetRelease: "1.0.0" }, registry),
  /SPENT_REGISTRY_REQUEST_IDENTITY_REQUIRED/,
);
assert.throws(
  () => validateSpentRegistry({ ...registry, sequence: 2 }, registrySignature, spentTrustStore),
  /EVAL_SIGNATURE_PAYLOAD_DIGEST_MISMATCH/,
);
assert.throws(
  () => validateSpentRegistry(registry, registrySignature, spentTrustStore, { minimumSequence: 2 }),
  /EVAL_SIGNATURE_ROLLBACK/,
);

const manifest = makeManifest();
const signedManifest = sign(canonicalManifestPayload(manifest));
const result = preflightDevelopmentRun({
  spentRegistry: registry,
  spentRegistrySignature: registrySignature,
  spentTrustStore,
  minimumSpentRegistrySequence: 1,
  expectedSpentRegistrySha256: registrySignature.payloadSha256,
  manifest,
  manifestSignature: signedManifest.signature,
  manifestTrustStore: signedManifest.trustStore,
});
assert.equal(result.pass, true);
assert.equal(result.recordCount, 1);
assert.equal(result.patientCount, 1);
assert.equal(result.clinicalAccuracyClaimed, false);

const unauthorizedSigner = sign(canonicalManifestPayload(manifest));
unauthorizedSigner.trustStore.keys[0].rightsAuthority = false;
assert.throws(
  () => validateManifestSignerAuthority(manifest, unauthorizedSigner.signature, unauthorizedSigner.trustStore),
  /DEVELOPMENT_MANIFEST_SIGNER_AUTHORITY/,
);
const outOfScopeSigner = sign(canonicalManifestPayload(manifest));
outOfScopeSigner.trustStore.keys[0].allowedDatasetIds = ["ECG-DATASET-OTHER"];
assert.throws(
  () => validateManifestSignerAuthority(manifest, outOfScopeSigner.signature, outOfScopeSigner.trustStore),
  /DEVELOPMENT_MANIFEST_SIGNER_SCOPE/,
);
assert.throws(
  () => validateManifestSignerAuthority(manifest, {}, {}),
  /DEVELOPMENT_MANIFEST_SIGNATURE/,
);

